def main(argv=None):
    d = ROOT / "viz" / "specs"
    d.mkdir(parents=True, exist_ok=True)
    from rrp.harness.yamlmini import load
    for name, fn, hdr in (("arm", arm_entries, "arm: R2 / BC / teacher v2 under grasp_v1 and grasp_v2, semantic edits"),
                          ("legged", legged_entries, "legged W8 contact_v2: context edits, teacher/BC refs, robustness"),
                          ("physics", physics_entries, "tracker validation v1 vs v2 contact, grasp rig v1 vs v2"),
                          ("dual", dual_entries, "dual W12: teacher v3 smoke, grasp_v2.1 peg failure")):
        es = [{k: v for k, v in e.items() if v is not None} for e in fn()]
        txt = dump(es, hdr)
        assert load(txt)["entries"] == es, name
        (d / f"{name}.yaml").write_text(txt)
        print(name, len(es), "entries", sum(len(e["seeds"]) * len(e.get("conditions", [1])) for e in es), "episodes")

