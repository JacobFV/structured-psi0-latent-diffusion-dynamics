def q(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(q(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {q(x)}" for k, x in v.items()) + "}"
    raise TypeError(v)


def dump(entries, header: str) -> str:
    out = [f"# {header}", "# generated by `rrp viz specs`; run on the PEER: python -m rrp.cli viz record --spec <this> --out ...",
           "entries:"]
    for e in entries:
        first = True
        for k, v in e.items():
            out.append(("  - " if first else "    ") + f"{k}: {q(v)}")
            first = False
    return "\n".join(out) + "\n"


